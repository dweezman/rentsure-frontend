export function buildInstallments(t: Tenancy): Installment[] {
  const step = scheduleMonths[t.schedule];
  const count = Math.max(1, Math.round(12 / step));
  return Array.from({ length: count }, (_, i) => ({
    id: `${t.id}_i${i + 1}`,
    tenancyId: t.id,
    dueDate: addMonths(t.startDate, i * step),
    amount: Math.round((t.annualRent * step) / 12),
  }));
}

